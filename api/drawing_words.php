function normalizeDrawWord(string $str): string {
    $str = strtolower(trim($str));
    $str = preg_replace('/[^a-z0-9 ]/', '', $str);
    $str = preg_replace('/\s+/', ' ', $str);
    return $str;
}

function drawWordMatches(int $idx, string $guess): bool {
    if (!isset(DRAW_WORDS[$idx])) return false;
    $entry = DRAW_WORDS[$idx];
    $g = normalizeDrawWord($guess);
    if ($g === '') return false;
    $candidates = array_map('normalizeDrawWord', array_merge([$entry['word']], $entry['aliases']));
    return in_array($g, $candidates, true);
}
